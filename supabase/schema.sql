create extension if not exists pgcrypto;

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    full_name text,
    shop_name text,
    phone text,
    email text,
    avatar_url text,
    role text not null default 'user' check (role in ('user', 'admin')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.product_categories (
    id bigint generated by default as identity primary key,
    name text not null unique,
    icon_url text,
    created_at timestamptz not null default now()
);

create table if not exists public.products (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.profiles (id) on delete cascade,
    category_id bigint references public.product_categories (id) on delete set null,
    name text not null,
    description text,
    price numeric(14, 2) not null check (price >= 0),
    stock integer not null default 0 check (stock >= 0),
    unit text not null default 'kg',
    weight numeric(12, 3) check (weight is null or weight >= 0),
    location text,
    thumbnail_url text,
    rating double precision not null default 0 check (rating between 0 and 5),
    total_review integer not null default 0 check (total_review >= 0),
    status text not null default 'active' check (status in ('active', 'inactive', 'sold_out')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.product_images (
    id uuid primary key default gen_random_uuid(),
    product_id uuid not null references public.products (id) on delete cascade,
    image_url text not null,
    is_primary boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.addresses (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.profiles (id) on delete cascade,
    recipient_name text,
    phone text,
    address text,
    city text,
    province text,
    latitude double precision,
    longitude double precision,
    is_default boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.orders (
    id uuid primary key default gen_random_uuid(),
    buyer_id uuid not null references public.profiles (id) on delete cascade,
    seller_id uuid not null references public.profiles (id) on delete cascade,
    address_id uuid references public.addresses (id) on delete set null,
    description text,
    total_amount numeric(14, 2) not null default 0 check (total_amount >= 0),
    capital_price numeric(14, 2) not null default 0 check (capital_price >= 0),
    shipping_cost numeric(14, 2) not null default 0 check (shipping_cost >= 0),
    grand_total numeric(14, 2) not null default 0 check (grand_total >= 0),
    payment_status text not null default 'pending'
        check (payment_status in ('pending', 'paid', 'failed', 'refunded')),
    order_status text not null default 'waiting'
        check (order_status in ('waiting', 'processing', 'shipped', 'completed', 'cancelled')),
    created_at timestamptz not null default now()
);

create table if not exists public.order_items (
    id uuid primary key default gen_random_uuid(),
    order_id uuid not null references public.orders (id) on delete cascade,
    product_id uuid not null references public.products (id) on delete restrict,
    qty integer not null check (qty > 0),
    price numeric(14, 2) not null check (price >= 0),
    subtotal numeric(14, 2) not null check (subtotal >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.banners (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references public.profiles (id) on delete cascade,
    title text,
    image_url text not null,
    link_url text,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create index if not exists products_user_id_idx on public.products (user_id);
